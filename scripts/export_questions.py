def load_sections(text):
    """(id, topic, normalized body, added). Sections tagged data-added (Task 3+)
    are valid override targets but never auto-matched from CORE_HINTS."""
    secs = []
    for m in re.finditer(r'<section class="sec" data-topic="([^"]+)" id="([^"]+)"( data-added="[^"]+")?>(.*?)</section>', text, re.S):
        body = htmllib.unescape(re.sub(r"<[^>]+>", " ", m.group(4)))
        secs.append((m.group(2), m.group(1), norm(body), bool(m.group(3))))
    return secs


def norm(s):
    s = re.sub(r"[·•∙⋅]", " ", str(s))
    s = re.sub(r"[–—−~]", "-", s)
    s = re.sub(r"[μµ]", "u", s)
    return re.sub(r"\s+", " ", s).strip().lower()


def is_english(s):
    letters = re.findall(r"[A-Za-z가-힣]", s)
    return bool(letters) and sum(c.isascii() for c in letters) / len(letters) > 0.9


def parse_choice_explanations(explain, n):
    out = [""] * n
    for line in explain.split("\n"):
        line = line.strip()
        if line and line[0] in CIRCLED:
            i = CIRCLED.index(line[0])
            if i < n:
                out[i] = line[1:].strip()
    return out


